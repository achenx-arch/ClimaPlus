CREATE TABLE ubicacion (
    id_ubicacion bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(100) NOT NULL,
    region character varying(100),
    pais character(2) NOT NULL,
    latitud numeric(7,4) NOT NULL,
    longitud numeric(8,4) NOT NULL,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_ubicacion PRIMARY KEY (id_ubicacion),
    CONSTRAINT ck_ubicacion_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_ubicacion_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_ubicacion_pais CHECK (pais ~ '^[A-Z]{2}$')
);

CREATE TABLE usuario (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(100) NOT NULL,
    correo character varying(150) NOT NULL,
    password_hash character varying(255) NOT NULL,
    rol character varying(20) NOT NULL DEFAULT 'USUARIO',
    activo boolean NOT NULL DEFAULT TRUE,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuario_correo_minusculas CHECK (correo = lower(correo)),
    CONSTRAINT ck_usuario_nombre_no_vacio CHECK (char_length(btrim(nombre)) > 0),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('USUARIO', 'ADMINISTRADOR'))
);

CREATE TABLE configuracion_alerta (
    id_configuracion bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_ubicacion bigint,
    tipo character varying(20) NOT NULL,
    valor_umbral numeric(5,2),
    activa boolean NOT NULL DEFAULT TRUE,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_configuracion_alerta PRIMARY KEY (id_configuracion),
    CONSTRAINT ck_configuracion_alerta_tipo CHECK (tipo IN ('LLUVIA', 'TEMPERATURA_ALTA', 'TEMPERATURA_BAJA')),
    CONSTRAINT ck_configuracion_alerta_umbral_rango CHECK (valor_umbral BETWEEN -50 AND 60),
    CONSTRAINT ck_configuracion_alerta_umbral_tipo CHECK ((tipo = 'LLUVIA' AND valor_umbral IS NULL) OR (tipo <> 'LLUVIA' AND valor_umbral IS NOT NULL)),
    CONSTRAINT fk_configuracion_alerta_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id_ubicacion) ON DELETE RESTRICT,
    CONSTRAINT fk_configuracion_alerta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE consulta_clima (
    id_consulta bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_ubicacion bigint NOT NULL,
    tipo_consulta character varying(20) NOT NULL,
    temperatura numeric(5,2),
    sensacion_termica numeric(5,2),
    humedad smallint,
    velocidad_viento numeric(5,2),
    codigo_condicion smallint,
    descripcion_condicion character varying(100),
    fecha_consulta timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_consulta_clima PRIMARY KEY (id_consulta),
    CONSTRAINT ck_consulta_clima_codigo_condicion CHECK (codigo_condicion BETWEEN 200 AND 899),
    CONSTRAINT ck_consulta_clima_humedad CHECK (humedad BETWEEN 0 AND 100),
    CONSTRAINT ck_consulta_clima_mediciones_tipo CHECK ((tipo_consulta = 'ACTUAL' AND num_nonnulls(temperatura, sensacion_termica, humedad, velocidad_viento, codigo_condicion, descripcion_condicion) = 6) OR (tipo_consulta = 'PRONOSTICO' AND num_nonnulls(temperatura, sensacion_termica, humedad, velocidad_viento, codigo_condicion, descripcion_condicion) = 0)),
    CONSTRAINT ck_consulta_clima_sensacion_termica CHECK (sensacion_termica BETWEEN -90 AND 70),
    CONSTRAINT ck_consulta_clima_temperatura CHECK (temperatura BETWEEN -90 AND 60),
    CONSTRAINT ck_consulta_clima_tipo_consulta CHECK (tipo_consulta IN ('ACTUAL', 'PRONOSTICO')),
    CONSTRAINT ck_consulta_clima_velocidad_viento CHECK (velocidad_viento >= 0),
    CONSTRAINT fk_consulta_clima_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id_ubicacion) ON DELETE RESTRICT,
    CONSTRAINT fk_consulta_clima_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE dispositivo (
    id_dispositivo bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_ubicacion bigint NOT NULL,
    nombre character varying(100) NOT NULL,
    api_key_hash character(64) NOT NULL,
    activo boolean NOT NULL DEFAULT TRUE,
    ultima_conexion timestamp with time zone,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_dispositivo PRIMARY KEY (id_dispositivo),
    CONSTRAINT fk_dispositivo_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id_ubicacion) ON DELETE RESTRICT,
    CONSTRAINT fk_dispositivo_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE favorito (
    id_favorito bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_ubicacion bigint NOT NULL,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_favorito PRIMARY KEY (id_favorito),
    CONSTRAINT fk_favorito_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id_ubicacion) ON DELETE RESTRICT,
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE lectura_sensor (
    id_lectura bigint GENERATED BY DEFAULT AS IDENTITY,
    id_dispositivo bigint NOT NULL,
    temperatura numeric(5,2),
    humedad numeric(5,2),
    lluvia boolean,
    luz smallint,
    fecha_lectura timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_lectura_sensor PRIMARY KEY (id_lectura),
    CONSTRAINT ck_lectura_sensor_al_menos_una_medicion CHECK (num_nonnulls(temperatura, humedad, lluvia, luz) >= 1),
    CONSTRAINT ck_lectura_sensor_humedad CHECK (humedad BETWEEN 0 AND 100),
    CONSTRAINT ck_lectura_sensor_luz CHECK (luz BETWEEN 0 AND 100),
    CONSTRAINT ck_lectura_sensor_temperatura CHECK (temperatura BETWEEN -40 AND 85),
    CONSTRAINT fk_lectura_sensor_dispositivo FOREIGN KEY (id_dispositivo) REFERENCES dispositivo (id_dispositivo) ON DELETE RESTRICT
);

CREATE TABLE alerta (
    id_alerta bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_ubicacion bigint NOT NULL,
    id_consulta bigint,
    id_lectura bigint,
    tipo character varying(20) NOT NULL,
    valor_detectado numeric(5,2),
    valor_umbral numeric(5,2),
    mensaje character varying(255) NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'NUEVA',
    fecha_generacion timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('NUEVA', 'LEIDA')),
    CONSTRAINT ck_alerta_origen_unico CHECK (num_nonnulls(id_consulta, id_lectura) = 1),
    CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('LLUVIA', 'TEMPERATURA_ALTA', 'TEMPERATURA_BAJA')),
    CONSTRAINT ck_alerta_valores_tipo CHECK ((tipo = 'LLUVIA' AND valor_detectado IS NULL AND valor_umbral IS NULL) OR (tipo <> 'LLUVIA' AND valor_detectado IS NOT NULL AND valor_umbral IS NOT NULL)),
    CONSTRAINT fk_alerta_consulta_clima FOREIGN KEY (id_consulta) REFERENCES consulta_clima (id_consulta) ON DELETE RESTRICT,
    CONSTRAINT fk_alerta_lectura_sensor FOREIGN KEY (id_lectura) REFERENCES lectura_sensor (id_lectura) ON DELETE RESTRICT,
    CONSTRAINT fk_alerta_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id_ubicacion) ON DELETE RESTRICT,
    CONSTRAINT fk_alerta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);


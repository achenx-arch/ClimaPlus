using ClimaPlus.Api.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace ClimaPlus.Api.Data;

/// <summary>
/// Contexto de Entity Framework Core de ClimaPlus.
/// Modelo aprobado: 8 tablas (docs/base-datos/modelo-relacional.puml y diccionario-datos.md).
/// </summary>
public class ClimaPlusDbContext : DbContext
{
    public ClimaPlusDbContext(DbContextOptions<ClimaPlusDbContext> options)
        : base(options)
    {
    }

    public DbSet<Usuario> Usuarios => Set<Usuario>();

    public DbSet<Ubicacion> Ubicaciones => Set<Ubicacion>();

    public DbSet<Favorito> Favoritos => Set<Favorito>();

    public DbSet<ConfiguracionAlerta> ConfiguracionesAlerta => Set<ConfiguracionAlerta>();

    public DbSet<ConsultaClima> ConsultasClima => Set<ConsultaClima>();

    public DbSet<Dispositivo> Dispositivos => Set<Dispositivo>();

    public DbSet<LecturaSensor> LecturasSensor => Set<LecturaSensor>();

    public DbSet<Alerta> Alertas => Set<Alerta>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        // D-06: BIGINT GENERATED BY DEFAULT AS IDENTITY en todas las tablas
        // (además, cada configuración lo declara explícitamente en su PK).
        modelBuilder.UseIdentityByDefaultColumns();

        // Aplica las 8 clases IEntityTypeConfiguration de Data/Configurations.
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(ClimaPlusDbContext).Assembly);
    }
}
